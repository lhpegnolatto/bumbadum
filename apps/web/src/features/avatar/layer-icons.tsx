import type { AppearanceLayer } from "@bumbadum/avatar";

/** What one icon of the Wardrobe picks: the skin tone or an appearance layer. */
export type EditorTab = "skinTone" | AppearanceLayer;

/** The icons in order, grouped by family: body, clothing, accessories (ADR-0023). */
export const TAB_FAMILIES = [
  ["skinTone", "hair"],
  ["top", "bottom", "overgarment"],
  ["footwear", "neckwear", "eyewear", "headwear"],
] as const satisfies readonly (readonly EditorTab[])[];

/** A crisp pixel-art icon in the current text colour, drawn on a 12×12 grid. */
export function LayerIcon({ tab, className }: { tab: EditorTab; className?: string }) {
  return (
    <svg
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden
      className={className}
    >
      <path d={pathOf(ICONS[tab])} />
    </svg>
  );
}

/** One unit square per `#`. */
function pathOf(grid: readonly string[]): string {
  return grid
    .flatMap((row, y) => [...row].map((cell, x) => (cell === "#" ? `M${x} ${y}h1v1h-1z` : "")))
    .join("");
}

