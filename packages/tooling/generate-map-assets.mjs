import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const tileSize = 16;
const mapName = process.argv.find((argument) => argument.startsWith("--map="))?.slice(6) ?? "plaza";
const maps = {
  plaza: {
    sourceRoot: path.resolve(import.meta.dirname, "../../assets/map/plaza"),
    sourceFile: "plaza.tmj",
    worldModule: "plaza-map.generated.ts",
    objectsModule: "plaza-objects.generated.ts",
    publicDirectory: "plaza",
    layers: { floor: "floor", objects: "objects", lights: "lights", collision: "collision" },
    prefix: "PLAZA",
  },
  "plaza-v2": {
    sourceRoot: path.resolve(import.meta.dirname, "../../assets/map/plaza-v2"),
    sourceFile: "plaza-v2.tmj",
    worldModule: "plaza-v2-map.generated.ts",
    objectsModule: "plaza-v2-objects.generated.ts",
    publicDirectory: "plaza-v2",
    layers: {
      floor: "floor",
      objects: "objects",
      lights: "lights",
      collision: "collision",
      collisionObjects: "collision-objects",
      track: "track",
      parking: "parking",
      startingGrid: "starting-grid",
      tennisCourt: "quadra_tenis",
      tennisLine: "fila_hall",
    },
    prefix: "PLAZA_V2",
  },
};
const config = maps[mapName];
if (!config) throw new Error(`unknown map ${mapName}; expected ${Object.keys(maps).join(" or ")}`);
const sourceRoot = config.sourceRoot;
const sourceFile = path.join(sourceRoot, config.sourceFile);
const walkabilityFile = path.resolve(import.meta.dirname, `../world/src/${config.worldModule}`);
const objectsFile = path.resolve(import.meta.dirname, `../game-engine/src/${config.objectsModule}`);
const publicRoot = path.resolve(
  import.meta.dirname,
  `../../apps/web/public/sprites/${config.publicDirectory}`,
);
/** Width of the object atlas; frames are packed in rows, with a transparent pixel between them. */
const atlasWidth = 512;
const atlasGap = 1;
const check = process.argv.includes("--check");

const map = JSON.parse(await readFile(sourceFile, "utf8"));
if (map.orientation !== "orthogonal" || map.infinite)
  throw new Error(`expected a finite orthogonal map: ${sourceFile}`);
if (map.tilewidth !== tileSize || map.tileheight !== tileSize)
  throw new Error(`expected ${tileSize}x${tileSize} px tiles: ${sourceFile}`);

const outputs = [
  { target: walkabilityFile, content: walkabilitySource(map) },
  await floorImage(map),
  ...(await objectOutputs(map)),
  await lightsImage(map),
];

for (const output of outputs) {
  if (check) {
    if (!(await isCurrent(output))) throw new Error(`stale generated map output: ${output.target}`);
  } else {
    await mkdir(path.dirname(output.target), { recursive: true });
    await writeFile(output.target, output.content);
  }
}
console.log(`${check ? "validated" : "generated"} the ${map.width}x${map.height} ${mapName} map`);

/** The rows `createMap` reads: `#` blocked, `.` walkable, `S` the spawn point. */
function walkabilitySource(map) {
  const collision = layer(map, config.layers.collision, "tilelayer");
  if (
    collision.width !== map.width ||
    collision.height !== map.height ||
    collision.data.length !== map.width * map.height
  )
    throw new Error(`collision layer is not ${map.width}x${map.height} tiles`);
  const blocked = (x, y) => collision.data[y * map.width + x] !== 0;

  const spawn = spawnTile(map);
  if (blocked(spawn.x, spawn.y)) throw new Error(`spawn point is on a blocked tile: ${key(spawn)}`);
  const unreachable = unreachableTiles(map, blocked, spawn);
  if (unreachable.length > 0)
    throw new Error(`walkable tiles unreachable from the spawn point: ${unreachable.join(" ")}`);

  const rows = Array.from({ length: map.height }, (_, y) =>
    Array.from({ length: map.width }, (_, x) => {
      if (x === spawn.x && y === spawn.y) return "S";
      return blocked(x, y) ? "#" : ".";
    }).join(""),
  );
  const generated = [
    `// Generated by pnpm --filter @bumbadum/world map:generate. Do not edit.`,
    `// biome-ignore format: generated data is serialized from Tiled.\nexport const ${config.prefix}_ROWS: readonly string[] = ${JSON.stringify(rows, null, 2)};`,
  ];
  if (config.layers.collisionObjects) {
    const collisionObjects = layer(map, config.layers.collisionObjects, "objectgroup");
    const track = layer(map, config.layers.track, "tilelayer");
    const parking = layer(map, config.layers.parking, "objectgroup");
    const startingGrid = layer(map, config.layers.startingGrid, "objectgroup");
    generated.push(
      `// biome-ignore format: generated data is serialized from Tiled.\nexport const ${config.prefix}_COLLISION_OBJECTS = ${JSON.stringify(
        collisionObjects.objects.map(rectangleObject),
        null,
        2,
      )} as const;`,
      `// biome-ignore format: generated data is serialized from Tiled.\nexport const ${config.prefix}_TRACK_ROWS: readonly string[] = ${JSON.stringify(
        tileRows(track, map, "track"),
        null,
        2,
      )};`,
      `// biome-ignore format: generated data is serialized from Tiled.\nexport const ${config.prefix}_PARKING_SPOTS = ${JSON.stringify(
        parking.objects.map(pointObject),
        null,
        2,
      )} as const;`,
      `// biome-ignore format: generated data is serialized from Tiled.\nexport const ${config.prefix}_STARTING_GRID = ${JSON.stringify(
        startingGrid.objects.map(pointObject),
        null,
        2,
      )} as const;`,
    );
  }
  if (config.layers.tennisCourt && config.layers.tennisLine) {
    const tennisCourt = layer(map, config.layers.tennisCourt, "objectgroup");
    const tennisLine = layer(map, config.layers.tennisLine, "objectgroup");
    generated.push(
      `// biome-ignore format: generated data is serialized from Tiled.\nexport const ${config.prefix}_TENNIS_COURT = ${JSON.stringify(
        tennisCourt.objects.map(metadataObject),
        null,
        2,
      )} as const;`,
      `// biome-ignore format: generated data is serialized from Tiled.\nexport const ${config.prefix}_TENNIS_LINE = ${JSON.stringify(
        tennisLine.objects.map(pointObject),
        null,
        2,
      )} as const;`,
    );
  }
  return `${generated.join("\n")}\n`;
}

/** The `floor` tile layer drawn as Tiled draws it: one tile per cell, empty cells transparent. */
async function floorImage(map) {
  const floor = layer(map, config.layers.floor, "tilelayer");
  expectPlainLayer(floor);
  if (floor.encoding !== undefined && floor.encoding !== "csv")
    throw new Error("floor layer must use the CSV tile layer format");
  if (
    floor.width !== map.width ||
    floor.height !== map.height ||
    floor.data.length !== map.width * map.height
  )
    throw new Error(`floor layer is not ${map.width}x${map.height} tiles`);
  const tilesets = map.tilesets.filter((candidate) => candidate.name === config.layers.floor);
  if (tilesets.length !== 1)
    throw new Error(`expected one embedded tileset named ${config.layers.floor}`);
  const [tileset] = tilesets;
  if (
    tileset.tilewidth !== tileSize ||
    tileset.tileheight !== tileSize ||
    tileset.margin !== 0 ||
    tileset.spacing !== 0 ||
    tileset.tileoffset !== undefined
  )
    throw new Error(
      `floor tileset must have ${tileSize}x${tileSize} px tiles and no margin, spacing or offset`,
    );

  const { data: sheet, info } = await sharp(path.join(sourceRoot, tileset.image))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  if (info.width !== tileset.imagewidth || info.height !== tileset.imageheight)
    throw new Error(`floor tileset image is not ${tileset.imagewidth}x${tileset.imageheight} px`);

  const width = map.width * tileSize;
  const height = map.height * tileSize;
  const pixels = Buffer.alloc(width * height * 4);
  floor.data.forEach((gid, cell) => {
    if (gid === 0) return;
    const tile = { x: cell % map.width, y: Math.floor(cell / map.width) };
    // Tiled keeps its flip and rotation flags in a gid's top bits.
    if (gid > 0x1fffffff)
      throw new Error(`flipped or rotated floor tiles are not supported: ${key(tile)}`);
    const index = gid - tileset.firstgid;
    if (index < 0 || index >= tileset.tilecount)
      throw new Error(`floor tile ${key(tile)} is not from the floor tileset: gid ${gid}`);
    const left = (index % tileset.columns) * tileSize;
    const top = Math.floor(index / tileset.columns) * tileSize;
    for (let y = 0; y < tileSize; y++) {
      const sourceStart = ((top + y) * info.width + left) * 4;
      const targetStart = ((tile.y * tileSize + y) * width + tile.x * tileSize) * 4;
      sheet.copy(pixels, targetStart, sourceStart, sourceStart + tileSize * 4);
    }
  });

  const content = await sharp(pixels, { raw: { width, height, channels: 4 } })
    .png({ compressionLevel: 9, adaptiveFiltering: false, palette: false })
    .toBuffer();
  return {
    target: path.join(publicRoot, "floor.png"),
    content,
    pixels: { width, height, data: pixels },
  };
}

/**
 * The `objects` tile objects: their tileset's images packed into one atlas, in tileset order,
 * and a game-engine module placing each object with its atlas frame. Tiled anchors a tile
 * object at its bottom-left corner, so its `y` is the sprite's bottom edge: its depth key.
 */
async function objectOutputs(map) {
  const objects = layer(map, config.layers.objects, "objectgroup");
  expectPlainLayer(objects);
  if (objects.draworder !== "topdown")
    throw new Error("objects layer must use the top down object drawing order");
  const tileset = await objectTileset(map);

  const frames = new Map();
  let shelf = { top: 0, left: 0, height: 0 };
  for (const tile of tileset.tiles) {
    if (tile.imagewidth > atlasWidth)
      throw new Error(`object image is wider than the ${atlasWidth} px atlas: ${tile.image}`);
    if (shelf.left + tile.imagewidth > atlasWidth)
      shelf = { top: shelf.top + shelf.height + atlasGap, left: 0, height: 0 };
    frames.set(tile.id, {
      tile,
      frame: { x: shelf.left, y: shelf.top, width: tile.imagewidth, height: tile.imageheight },
    });
    shelf.left += tile.imagewidth + atlasGap;
    shelf.height = Math.max(shelf.height, tile.imageheight);
  }

  const height = shelf.top + shelf.height;
  const pixels = Buffer.alloc(atlasWidth * height * 4);
  for (const { tile, frame } of frames.values()) {
    const { data, info } = await sharp(path.join(sourceRoot, tile.image))
      .ensureAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });
    if (info.width !== tile.imagewidth || info.height !== tile.imageheight)
      throw new Error(`${tile.image} is not ${tile.imagewidth}x${tile.imageheight} px`);
    for (let y = 0; y < frame.height; y++) {
      const sourceStart = y * frame.width * 4;
      const targetStart = ((frame.y + y) * atlasWidth + frame.x) * 4;
      data.copy(pixels, targetStart, sourceStart, sourceStart + frame.width * 4);
    }
  }
  const atlas = await sharp(pixels, { raw: { width: atlasWidth, height, channels: 4 } })
    .png({ compressionLevel: 9, adaptiveFiltering: false, palette: false })
    .toBuffer();

  const placed = objects.objects.map((object) => {
    const label = `object ${object.id} (${object.name || "unnamed"})`;
    if (object.gid === undefined) throw new Error(`${label} is not a tile object`);
    // Tiled keeps its flip and rotation flags in a gid's top bits.
    if (object.gid > 0x1fffffff) throw new Error(`${label} is flipped, which is not supported`);
    const placement = frames.get(object.gid - tileset.firstgid);
    if (!placement) throw new Error(`${label} is not from the objects tileset: gid ${object.gid}`);
    if (!object.visible) throw new Error(`${label} is hidden`);
    if (object.rotation !== 0) throw new Error(`${label} is rotated, which is not supported`);
    if (!Number.isInteger(object.x) || !Number.isInteger(object.y))
      throw new Error(`${label} is not on whole pixels: ${object.x},${object.y}`);
    const { frame, tile } = placement;
    if (object.width !== frame.width || object.height !== frame.height)
      throw new Error(
        `${label} is ${object.width}x${object.height} px, not its image's ${frame.width}x${frame.height}`,
      );
    const animation = tile.animation?.map(({ tileid, duration }) => ({
      frame: frames.get(tileid).frame,
      duration,
    }));
    return {
      name: object.name,
      frame,
      x: object.x,
      y: object.y - frame.height,
      base: object.y,
      ...(animation && { animation }),
    };
  });

  const module =
    `// Generated by pnpm --filter @bumbadum/world map:generate. Do not edit.\n\n` +
    `/**\n` +
    ` * The plaza's objects: each one's frame in objects.png, the world pixel where its top-left\n` +
    ` * corner is drawn, and its base (bottom edge), which places it in depth order. An object\n` +
    ` * with an Ambient animation also lists every frame it loops through, with its duration in\n` +
    ` * milliseconds; each frame is the size of the first.\n` +
    ` */\n` +
    `// biome-ignore format: generated data is serialized from Tiled.\nexport const ${config.prefix}_OBJECTS: readonly {\n` +
    `  name: string;\n` +
    `  frame: { x: number; y: number; width: number; height: number };\n` +
    `  x: number;\n` +
    `  y: number;\n` +
    `  base: number;\n` +
    `  animation?: readonly {\n` +
    `    frame: { x: number; y: number; width: number; height: number };\n` +
    `    duration: number;\n` +
    `  }[];\n` +
    `}[] = [\n` +
    placed.map((object) => `  ${JSON.stringify(object)},\n`).join("") +
    `];\n`;

  return [
    {
      target: path.join(publicRoot, "objects.png"),
      content: atlas,
      pixels: { width: atlasWidth, height, data: pixels },
    },
    { target: objectsFile, content: module },
  ];
}

/** The image-collection tileset named `objects`, with each tile drawn whole and unshifted. */
async function objectTileset(map) {
  const tilesets = await Promise.all(
    map.tilesets.map(async (entry) =>
      entry.source
        ? {
            ...JSON.parse(await readFile(path.join(sourceRoot, entry.source), "utf8")),
            firstgid: entry.firstgid,
          }
        : entry,
    ),
  );
  const found = tilesets.filter((candidate) => candidate.name === config.layers.objects);
  if (found.length !== 1) throw new Error(`expected one tileset named ${config.layers.objects}`);
  const [tileset] = found;
  if (tileset.columns !== 0 || tileset.image !== undefined || !Array.isArray(tileset.tiles))
    throw new Error("objects tileset must be a collection of images");
  const unsupported = [
    tileset.tileoffset !== undefined && "tile offset",
    !["unspecified", "bottomleft", undefined].includes(tileset.objectalignment) &&
      "object alignment",
    ![undefined, "tile"].includes(tileset.tilerendersize) && "tile render size",
  ].filter(Boolean);
  if (unsupported.length > 0)
    throw new Error(`objects tileset uses unsupported settings: ${unsupported.join(", ")}`);
  for (const tile of tileset.tiles) {
    if (!tile.image) throw new Error(`objects tile ${tile.id} has no image`);
    if (tile.x || tile.y || tile.width !== undefined || tile.height !== undefined)
      throw new Error(`objects tile ${tile.id} uses only part of its image`);
    if (tile.animation) expectAnimation(tileset, tile);
  }
  return tileset;
}

/**
 * An animated tile's frames are tiles of the same tileset, each the size of the tile itself, so
 * every frame keeps the object's base and depth order (Tiled cannot animate across tilesets).
 */
function expectAnimation(tileset, tile) {
  const label = `objects tile ${tile.id} (${tile.image})`;
  if (!Array.isArray(tile.animation) || tile.animation.length === 0)
    throw new Error(`${label} has an empty animation`);
  for (const { tileid, duration } of tile.animation) {
    const frame = tileset.tiles.find((candidate) => candidate.id === tileid);
    if (!frame)
      throw new Error(`${label} animates a frame that is not in the objects tileset: ${tileid}`);
    if (frame.imagewidth !== tile.imagewidth || frame.imageheight !== tile.imageheight)
      throw new Error(`${label} animates frame ${frame.image}, which is not its size`);
    if (!Number.isInteger(duration) || duration <= 0)
      throw new Error(`${label} has a frame lasting ${duration} ms`);
  }
}

/** The `lights` image layer's image, copied byte for byte. */
async function lightsImage(map) {
  const lights = layer(map, config.layers.lights, "imagelayer");
  expectPlainLayer(lights);
  if (lights.repeatx || lights.repeaty) throw new Error("lights layer must not repeat");
  const content = await readFile(path.join(sourceRoot, lights.image));
  const { width, height } = await sharp(content).metadata();
  if (width !== map.width * tileSize || height !== map.height * tileSize)
    throw new Error(`lights image is not ${map.width * tileSize}x${map.height * tileSize} px`);
  return { target: path.join(publicRoot, "lights.png"), content };
}

function tileRows(tileLayer, map, label) {
  if (
    tileLayer.width !== map.width ||
    tileLayer.height !== map.height ||
    tileLayer.data.length !== map.width * map.height
  )
    throw new Error(`${label} layer is not ${map.width}x${map.height} tiles`);
  return Array.from({ length: map.height }, (_, y) =>
    Array.from({ length: map.width }, (_, x) =>
      tileLayer.data[y * map.width + x] === 0 ? "." : "#",
    ).join(""),
  );
}

function rectangleObject(object) {
  const label = `collision object ${object.id} (${object.name || "unnamed"})`;
  if (object.point || object.ellipse || object.polygon || object.polyline)
    throw new Error(`${label} must be an axis-aligned rectangle`);
  if (object.rotation !== 0) throw new Error(`${label} is rotated, which is not supported`);
  if (!Number.isInteger(object.x) || !Number.isInteger(object.y))
    throw new Error(`${label} is not on whole pixels: ${object.x},${object.y}`);
  if (!Number.isInteger(object.width) || !Number.isInteger(object.height))
    throw new Error(`${label} has a non-integer size`);
  return {
    name: object.name,
    x: object.x,
    y: object.y,
    width: object.width,
    height: object.height,
  };
}

function pointObject(object) {
  const label = `point object ${object.id} (${object.name || "unnamed"})`;
  if (!object.point) throw new Error(`${label} must be a point`);
  if (object.rotation !== 0) throw new Error(`${label} is rotated, which is not supported`);
  if (!Number.isInteger(object.x) || !Number.isInteger(object.y))
    throw new Error(`${label} is not on whole pixels: ${object.x},${object.y}`);
  const properties = Object.fromEntries(
    (object.properties ?? []).map(({ name, value }) => [name, value]),
  );
  return { name: object.name, x: object.x, y: object.y, ...properties };
}

function metadataObject(object) {
  const label = `map object ${object.id} (${object.name || "unnamed"})`;
  if (object.rotation !== 0) throw new Error(`${label} is rotated, which is not supported`);
  if (!Number.isInteger(object.x) || !Number.isInteger(object.y))
    throw new Error(`${label} is not on whole pixels: ${object.x},${object.y}`);
  const properties = Object.fromEntries(
    (object.properties ?? []).map(({ name, value }) => [name, value]),
  );
  return {
    name: object.name,
    type: object.type,
    x: object.x,
    y: object.y,
    width: object.width,
    height: object.height,
    point: Boolean(object.point),
    ...properties,
  };
}

/** Rejects layer settings the engine would not reproduce: it draws each layer as authored. */
function expectPlainLayer(drawn) {
  const unsupported = [
    !drawn.visible && "hidden",
    drawn.opacity !== 1 && "opacity",
    (drawn.x || drawn.y || drawn.offsetx || drawn.offsety) && "offset",
    ((drawn.parallaxx ?? 1) !== 1 || (drawn.parallaxy ?? 1) !== 1) && "parallax",
    drawn.tintcolor !== undefined && "tint",
  ].filter(Boolean);
  if (unsupported.length > 0)
    throw new Error(`${drawn.name} layer uses unsupported settings: ${unsupported.join(", ")}`);
}

/** Composed images compare by decoded pixels, so another PNG encoder cannot make them stale. */
async function isCurrent({ target, content, pixels }) {
  const existing = await readFile(target).catch(() => undefined);
  if (!existing) return false;
  if (!pixels) return existing.equals(Buffer.from(content));
  const { data, info } = await sharp(existing)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  return info.width === pixels.width && info.height === pixels.height && data.equals(pixels.data);
}

function spawnTile(map) {
  const spawns = map.layers
    .filter((candidate) => candidate.type === "objectgroup")
    .flatMap((group) => group.objects)
    .filter((object) => object.name === "spawn");
  if (spawns.length !== 1)
    throw new Error(`expected one object named spawn, found ${spawns.length}`);
  const [spawn] = spawns;
  if (!spawn.point) throw new Error("the spawn object must be a point");
  const tile = { x: Math.floor(spawn.x / tileSize), y: Math.floor(spawn.y / tileSize) };
  if (tile.x < 0 || tile.y < 0 || tile.x >= map.width || tile.y >= map.height)
    throw new Error(`spawn point is outside the map: ${key(tile)}`);
  return tile;
}

function unreachableTiles(map, blocked, spawn) {
  const reached = new Set([key(spawn)]);
  const frontier = [spawn];
  for (let tile = frontier.pop(); tile; tile = frontier.pop()) {
    for (const [dx, dy] of [
      [1, 0],
      [-1, 0],
      [0, 1],
      [0, -1],
    ]) {
      const next = { x: tile.x + dx, y: tile.y + dy };
      if (next.x < 0 || next.y < 0 || next.x >= map.width || next.y >= map.height) continue;
      if (blocked(next.x, next.y) || reached.has(key(next))) continue;
      reached.add(key(next));
      frontier.push(next);
    }
  }
  const unreachable = [];
  for (let y = 0; y < map.height; y++)
    for (let x = 0; x < map.width; x++)
      if (!blocked(x, y) && !reached.has(key({ x, y }))) unreachable.push(key({ x, y }));
  return unreachable;
}

function layer(map, name, type) {
  const found = map.layers.filter((candidate) => candidate.name === name);
  if (found.length !== 1 || found[0].type !== type)
    throw new Error(`expected one ${type} named ${name}: ${sourceFile}`);
  return found[0];
}

function key(tile) {
  return `${tile.x},${tile.y}`;
}
