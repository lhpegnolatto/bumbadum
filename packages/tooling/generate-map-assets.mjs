import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const tileSize = 16;
const sourceRoot = path.resolve(import.meta.dirname, "../../assets/map/plaza");
const sourceFile = path.join(sourceRoot, "plaza.tmj");
const walkabilityFile = path.resolve(import.meta.dirname, "../world/src/plaza-map.generated.ts");
const publicRoot = path.resolve(import.meta.dirname, "../../apps/web/public/sprites/plaza");
const check = process.argv.includes("--check");

const map = JSON.parse(await readFile(sourceFile, "utf8"));
if (map.orientation !== "orthogonal" || map.infinite)
  throw new Error(`expected a finite orthogonal map: ${sourceFile}`);
if (map.tilewidth !== tileSize || map.tileheight !== tileSize)
  throw new Error(`expected ${tileSize}x${tileSize} px tiles: ${sourceFile}`);

const outputs = [
  { target: walkabilityFile, content: walkabilitySource(map) },
  await floorImage(map),
  await lightsImage(map),
];

for (const output of outputs) {
  if (check) {
    if (!(await isCurrent(output))) throw new Error(`stale generated map output: ${output.target}`);
  } else {
    await mkdir(path.dirname(output.target), { recursive: true });
    await writeFile(output.target, output.content);
  }
}
console.log(`${check ? "validated" : "generated"} the ${map.width}x${map.height} plaza map`);

/** The rows `createMap` reads: `#` blocked, `.` walkable, `S` the spawn point. */
function walkabilitySource(map) {
  const collision = layer(map, "collision", "tilelayer");
  if (
    collision.width !== map.width ||
    collision.height !== map.height ||
    collision.data.length !== map.width * map.height
  )
    throw new Error(`collision layer is not ${map.width}x${map.height} tiles`);
  const blocked = (x, y) => collision.data[y * map.width + x] !== 0;

  const spawn = spawnTile(map);
  if (blocked(spawn.x, spawn.y)) throw new Error(`spawn point is on a blocked tile: ${key(spawn)}`);
  const unreachable = unreachableTiles(map, blocked, spawn);
  if (unreachable.length > 0)
    throw new Error(`walkable tiles unreachable from the spawn point: ${unreachable.join(" ")}`);

  const rows = Array.from({ length: map.height }, (_, y) =>
    Array.from({ length: map.width }, (_, x) => {
      if (x === spawn.x && y === spawn.y) return "S";
      return blocked(x, y) ? "#" : ".";
    }).join(""),
  );
  return (
    `// Generated by pnpm --filter @bumbadum/world map:generate. Do not edit.\n` +
    `export const PLAZA_ROWS: readonly string[] = ${JSON.stringify(rows, null, 2)};\n`
  );
}

/** The `floor` tile layer drawn as Tiled draws it: one tile per cell, empty cells transparent. */
async function floorImage(map) {
  const floor = layer(map, "floor", "tilelayer");
  expectPlainLayer(floor);
  if (floor.encoding !== undefined && floor.encoding !== "csv")
    throw new Error("floor layer must use the CSV tile layer format");
  if (
    floor.width !== map.width ||
    floor.height !== map.height ||
    floor.data.length !== map.width * map.height
  )
    throw new Error(`floor layer is not ${map.width}x${map.height} tiles`);
  const tilesets = map.tilesets.filter((candidate) => candidate.name === "floor");
  if (tilesets.length !== 1) throw new Error("expected one embedded tileset named floor");
  const [tileset] = tilesets;
  if (
    tileset.tilewidth !== tileSize ||
    tileset.tileheight !== tileSize ||
    tileset.margin !== 0 ||
    tileset.spacing !== 0 ||
    tileset.tileoffset !== undefined
  )
    throw new Error(
      `floor tileset must have ${tileSize}x${tileSize} px tiles and no margin, spacing or offset`,
    );

  const { data: sheet, info } = await sharp(path.join(sourceRoot, tileset.image))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  if (info.width !== tileset.imagewidth || info.height !== tileset.imageheight)
    throw new Error(`floor tileset image is not ${tileset.imagewidth}x${tileset.imageheight} px`);

  const width = map.width * tileSize;
  const height = map.height * tileSize;
  const pixels = Buffer.alloc(width * height * 4);
  floor.data.forEach((gid, cell) => {
    if (gid === 0) return;
    const tile = { x: cell % map.width, y: Math.floor(cell / map.width) };
    // Tiled keeps its flip and rotation flags in a gid's top bits.
    if (gid > 0x1fffffff)
      throw new Error(`flipped or rotated floor tiles are not supported: ${key(tile)}`);
    const index = gid - tileset.firstgid;
    if (index < 0 || index >= tileset.tilecount)
      throw new Error(`floor tile ${key(tile)} is not from the floor tileset: gid ${gid}`);
    const left = (index % tileset.columns) * tileSize;
    const top = Math.floor(index / tileset.columns) * tileSize;
    for (let y = 0; y < tileSize; y++) {
      const sourceStart = ((top + y) * info.width + left) * 4;
      const targetStart = ((tile.y * tileSize + y) * width + tile.x * tileSize) * 4;
      sheet.copy(pixels, targetStart, sourceStart, sourceStart + tileSize * 4);
    }
  });

  const content = await sharp(pixels, { raw: { width, height, channels: 4 } })
    .png({ compressionLevel: 9, adaptiveFiltering: false, palette: false })
    .toBuffer();
  return {
    target: path.join(publicRoot, "floor.png"),
    content,
    pixels: { width, height, data: pixels },
  };
}

/** The `lights` image layer's image, copied byte for byte. */
async function lightsImage(map) {
  const lights = layer(map, "lights", "imagelayer");
  expectPlainLayer(lights);
  if (lights.repeatx || lights.repeaty) throw new Error("lights layer must not repeat");
  const content = await readFile(path.join(sourceRoot, lights.image));
  const { width, height } = await sharp(content).metadata();
  if (width !== map.width * tileSize || height !== map.height * tileSize)
    throw new Error(`lights image is not ${map.width * tileSize}x${map.height * tileSize} px`);
  return { target: path.join(publicRoot, "lights.png"), content };
}

/** Rejects layer settings the engine would not reproduce: it draws each layer as authored. */
function expectPlainLayer(drawn) {
  const unsupported = [
    !drawn.visible && "hidden",
    drawn.opacity !== 1 && "opacity",
    (drawn.x || drawn.y || drawn.offsetx || drawn.offsety) && "offset",
    ((drawn.parallaxx ?? 1) !== 1 || (drawn.parallaxy ?? 1) !== 1) && "parallax",
    drawn.tintcolor !== undefined && "tint",
  ].filter(Boolean);
  if (unsupported.length > 0)
    throw new Error(`${drawn.name} layer uses unsupported settings: ${unsupported.join(", ")}`);
}

/** Composed images compare by decoded pixels, so another PNG encoder cannot make them stale. */
async function isCurrent({ target, content, pixels }) {
  const existing = await readFile(target).catch(() => undefined);
  if (!existing) return false;
  if (!pixels) return existing.equals(Buffer.from(content));
  const { data, info } = await sharp(existing)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  return info.width === pixels.width && info.height === pixels.height && data.equals(pixels.data);
}

function spawnTile(map) {
  const spawns = map.layers
    .filter((candidate) => candidate.type === "objectgroup")
    .flatMap((group) => group.objects)
    .filter((object) => object.name === "spawn");
  if (spawns.length !== 1)
    throw new Error(`expected one object named spawn, found ${spawns.length}`);
  const [spawn] = spawns;
  if (!spawn.point) throw new Error("the spawn object must be a point");
  const tile = { x: Math.floor(spawn.x / tileSize), y: Math.floor(spawn.y / tileSize) };
  if (tile.x < 0 || tile.y < 0 || tile.x >= map.width || tile.y >= map.height)
    throw new Error(`spawn point is outside the map: ${key(tile)}`);
  return tile;
}

function unreachableTiles(map, blocked, spawn) {
  const reached = new Set([key(spawn)]);
  const frontier = [spawn];
  for (let tile = frontier.pop(); tile; tile = frontier.pop()) {
    for (const [dx, dy] of [
      [1, 0],
      [-1, 0],
      [0, 1],
      [0, -1],
    ]) {
      const next = { x: tile.x + dx, y: tile.y + dy };
      if (next.x < 0 || next.y < 0 || next.x >= map.width || next.y >= map.height) continue;
      if (blocked(next.x, next.y) || reached.has(key(next))) continue;
      reached.add(key(next));
      frontier.push(next);
    }
  }
  const unreachable = [];
  for (let y = 0; y < map.height; y++)
    for (let x = 0; x < map.width; x++)
      if (!blocked(x, y) && !reached.has(key({ x, y }))) unreachable.push(key({ x, y }));
  return unreachable;
}

function layer(map, name, type) {
  const found = map.layers.filter((candidate) => candidate.name === name);
  if (found.length !== 1 || found[0].type !== type)
    throw new Error(`expected one ${type} named ${name}: ${sourceFile}`);
  return found[0];
}

function key(tile) {
  return `${tile.x},${tile.y}`;
}
